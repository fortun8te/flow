import AppKit
import Testing
@testable import Voice

@Suite("Dictation clipboard writes carry the clipboard-manager markers")
struct DictationPasteboardTests {
    @Test("Text is written and the transient, auto-generated and concealed markers are set")
    func writesTextWithMarkers() {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("flow.tests.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        #expect(DictationPasteboard.write("Hello there", to: pasteboard))
        #expect(pasteboard.string(forType: .string) == "Hello there")
        let types = pasteboard.types ?? []
        #expect(types.contains(DictationPasteboard.transient))
        #expect(types.contains(DictationPasteboard.autoGenerated))
        #expect(types.contains(DictationPasteboard.concealed))
    }

    @Test("A second write replaces the first, without leftover content")
    func replaces() {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("flow.tests.\(UUID().uuidString)"))
        defer { pasteboard.releaseGlobally() }
        DictationPasteboard.write("first", to: pasteboard)
        DictationPasteboard.write("second", to: pasteboard)
        #expect(pasteboard.string(forType: .string) == "second")
    }
}
